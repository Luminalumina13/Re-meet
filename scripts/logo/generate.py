#!/usr/bin/env python3
"""Builds the logo files from one geometry: src/components/LogoMark.tsx, public/favicon.svg and (with ImageMagick) the raster icons.

Three chevron streams (blue, yellow, green) converge on a four-point star. The star is dark on light backgrounds and white on dark ones,
and the fading chevrons use lighter tints on dark. `full` is the header mark, `icon` the simplified one (two chevrons per stream) for
the favicon and app icons. See docs/logo.md.

usage: python3 scripts/logo/generate.py                 (run from the repository root; rewrites the site files)
       python3 scripts/logo/generate.py --avatars DIR   (square 640 px avatars for bots and chats, dark and light)
"""
import math, os, subprocess, sys, tempfile

BASE = {"b": "#4F73FF", "y": "#FFC41F", "g": "#12B5A3"}
ARM = {"b": 180, "y": 300, "g": 60}  # where each stream comes from (screen degrees)
STAR = "M0-10C.55-2.7 2.7-.55 10 0C2.7.55.55 2.7 0 10C-.55 2.7-2.7.55-10 0C-2.7-.55-.55-2.7 0-10Z"
NAVY = "#0F172A"
CFG = {
    "full": dict(ds=[28, 21.5, 15], ops=[0.42, 0.72, 1], w=3.2, L=8.5, sr=11.5),
    "icon": dict(ds=[26, 16.5], ops=[0.7, 1], w=4.4, L=10, sr=12.5),
}

def tint(hex_, t):
    n = int(hex_[1:], 16)
    return "#%02X%02X%02X" % tuple(round(v + (255 - v) * t) for v in ((n >> 16) & 255, (n >> 8) & 255, n & 255))

DARK = {k: tint(v, 0.22) for k, v in BASE.items()}

def dark_op(o):
    return round(min(1, 0.45 + 0.55 * o), 2)

def geometry(cfg):
    """Chevron paths per stream and the square viewBox that fits every point, tails included, centred."""
    pts, chevrons = [], []
    for key, th in ARM.items():
        for i, d in enumerate(cfg["ds"]):
            p = (32 + d * math.cos(math.radians(th)), 32 + d * math.sin(math.radians(th)))
            a, b = math.radians(th + 42), math.radians(th - 42)
            e1 = (p[0] + cfg["L"] * math.cos(a), p[1] + cfg["L"] * math.sin(a))
            e2 = (p[0] + cfg["L"] * math.cos(b), p[1] + cfg["L"] * math.sin(b))
            pts += [p, e1, e2]
            chevrons.append((key, i, f"M{e1[0]:.2f} {e1[1]:.2f}L{p[0]:.2f} {p[1]:.2f}L{e2[0]:.2f} {e2[1]:.2f}"))
    sr = cfg["sr"]
    pts += [(32 - sr, 32), (32 + sr, 32), (32, 32 - sr), (32, 32 + sr)]
    pad = cfg["w"] / 2 + 1.5
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    minx, maxx, miny, maxy = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
    size = max(maxx - minx, maxy - miny)
    vx, vy = (minx + maxx) / 2 - size / 2, (miny + maxy) / 2 - size / 2
    return chevrons, (round(vx, 2), round(vy, 2), round(size, 2))

def star_el(cfg, fill):
    return f'<path transform="translate(32 32) scale({cfg["sr"] / 10:g})" d="{STAR}" fill="{fill}"/>'

# ---- React component (colours come from CSS variables, see globals.css) ----
def component():
    cfg = CFG["full"]
    chevrons, vb = geometry(cfg)
    paths = "\n".join(
        f'      <path d="{d}" style={{{{ stroke: "var(--lm-{k})", opacity: "var(--lm-o{i})" }}}} />' for k, i, d in chevrons
    )
    return f'''// GENERATED by scripts/logo/generate.py. Do not edit by hand.
import type {{ CSSProperties }} from "react";

/** The Re:meeet mark: three chevron streams converge on a star. Colours follow the theme through the --lm-* variables in globals.css. */
export function LogoMark({{ size = 36, className }}: {{ size?: number; className?: string }}) {{
  return (
    <svg width={{size}} height={{size}} viewBox="{vb[0]} {vb[1]} {vb[2]} {vb[2]}" fill="none" strokeWidth={{{cfg["w"]}}} strokeLinecap="round" strokeLinejoin="round" aria-hidden className={{className}}>
{paths}
      <path transform="translate(32 32) scale({cfg["sr"] / 10:g})" d="{STAR}" style={{{{ fill: "var(--lm-star)" }} as CSSProperties}} />
    </svg>
  );
}}
'''

# ---- adaptive favicon: transparent, dark star and bright chevrons on light tabs, white star and tints on dark ----
def favicon_svg():
    cfg = CFG["icon"]
    chevrons, vb = geometry(cfg)
    css = ".s{fill:#0B1220}" + "".join(f".{k}{{stroke:{BASE[k]}}}" for k in BASE)
    css += "".join(f".o{i}{{opacity:{o}}}" for i, o in enumerate(cfg["ops"]))
    dark = ".s{fill:#fff}" + "".join(f".{k}{{stroke:{DARK[k]}}}" for k in DARK) + "".join(f".o{i}{{opacity:{dark_op(o)}}}" for i, o in enumerate(cfg["ops"]))
    body = "".join(f'<path class="{k} o{i}" d="{d}"/>' for k, i, d in chevrons)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="{vb[0]} {vb[1]} {vb[2]} {vb[2]}" fill="none" '
            f'stroke-width="{cfg["w"]}" stroke-linecap="round" stroke-linejoin="round"><style>{css}@media (prefers-color-scheme:dark){{{dark}}}</style>'
            f'{body}<path class="s" transform="translate(32 32) scale({cfg["sr"] / 10:g})" d="{STAR}"/></svg>\n')

# ---- dark tile for the raster icons (ICO, PNG, apple-touch-icon): static, no media queries ----
def tile_svg():
    cfg = CFG["icon"]
    chevrons, vb = geometry(cfg)
    s = 46 / vb[2]
    body = "".join(f'<path d="{d}" stroke="{DARK[k]}" opacity="{dark_op(cfg["ops"][i])}"/>' for k, i, d in chevrons)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="{NAVY}"/>'
            f'<g transform="translate(9 9) scale({s:.5f}) translate({-vb[0]} {-vb[1]})" fill="none" stroke-width="{cfg["w"]}" stroke-linecap="round" stroke-linejoin="round">'
            f'{body}{star_el(cfg, "#fff")}</g></svg>\n')

def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)

def avatar_svg(theme):
    """Square, full-bleed avatar for bots and chats. Telegram crops it to a circle, so the mark stays inside the middle ~55%."""
    cfg = CFG["icon"]
    chevrons, vb = geometry(cfg)
    dark = theme == "dark"
    bg, star = (NAVY, "#fff") if dark else ("#F5F6F8", "#0B1220")
    s = 560 / vb[2]  # 1024 canvas, mark about 55 % of it
    off = (1024 - 560) / 2
    body = "".join(
        f'<path d="{d}" stroke="{DARK[k] if dark else BASE[k]}" opacity="{dark_op(cfg["ops"][i]) if dark else cfg["ops"][i]}"/>' for k, i, d in chevrons
    )
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><rect width="1024" height="1024" fill="{bg}"/>'
            f'<g transform="translate({off} {off}) scale({s:.5f}) translate({-vb[0]} {-vb[1]})" fill="none" stroke-width="{cfg["w"]}" stroke-linecap="round" stroke-linejoin="round">'
            f'{body}{star_el(cfg, star)}</g></svg>\n')

def raster(src, out, size):
    subprocess.run(["magick", "-background", "none", "-density", "1200", src, "-resize", f"{size}x{size}", out], check=True)

def main():
    if "--avatars" in sys.argv:
        out_dir = sys.argv[sys.argv.index("--avatars") + 1]
        os.makedirs(out_dir, exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            for theme in ("dark", "light"):
                svg = os.path.join(tmp, f"{theme}.svg")
                write(svg, avatar_svg(theme))
                raster(svg, os.path.join(out_dir, f"remeeet-avatar-{theme}.png"), 640)
        print("avatars written to", out_dir)
        return
    write("src/components/LogoMark.tsx", component())
    write("public/favicon.svg", favicon_svg())
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "tile.svg")
        write(src, tile_svg())
        raster(src, "public/icon-512.png", 512)
        raster(src, "public/icon-192.png", 192)
        raster(src, "public/apple-touch-icon.png", 180)
        a, b = os.path.join(tmp, "a.png"), os.path.join(tmp, "b.png")
        raster(src, a, 32)
        raster(src, b, 48)
        subprocess.run(["magick", a, b, "public/favicon.ico"], check=True)
    print("logo files written")

if __name__ == "__main__":
    main()
