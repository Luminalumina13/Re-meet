#!/usr/bin/env python3
"""Builds src/lib/data/airportsExtra.ts. See docs/airports.md for the inputs and how to refresh them.

usage: generate.py <workdir>
workdir holds airports.csv (OurAirports), tz.json ({iata: tz}) and wd.json (Wikidata: [{iata, en, uk}]).
"""
import csv, collections, json, re, sys, unicodedata

W = sys.argv[1].rstrip("/") + "/"
SKIP = {"RU", "BY", "KP"}  # no flights are sold there; new Ukrainian airports are closed, the curated ones stay
OVERRIDE_CITY = {  # one metropolitan area, one city (OurAirports names the suburb)
    "NRT": "Tokyo", "IAD": "Washington", "GIG": "Rio de Janeiro", "EZE": "Buenos Aires", "KUL": "Kuala Lumpur",
    "SZB": "Kuala Lumpur", "DWC": "Dubai", "TPE": "Taipei", "TSA": "Taipei", "BUR": "Los Angeles", "LGB": "Los Angeles",
    "SNA": "Los Angeles", "NGO": "Nagoya",
}
OVERRIDE_NAME = {"TFN": "Tenerife North"}
MANUAL_UK = {
    "Taipei": "Тайбей", "Nagoya": "Нагоя", "Kuala Lumpur": "Куала-Лумпур", "Washington": "Вашингтон", "Tokyo": "Токіо",
    "Rio de Janeiro": "Ріо-де-Жанейро", "Buenos Aires": "Буенос-Айрес", "Los Angeles": "Лос-Анджелес", "Dubai": "Дубай",
}

core_ts = open("src/lib/data/airports.ts", encoding="utf-8").read()
have = set(re.findall(r'\["([A-Z]{3})",', core_ts))
cur_country = {}
for _, city, cc in re.findall(r'\["([A-Z]{3})", "[^"]*", "([^"]*)", "([A-Z]{2})"', core_ts):
    cur_country.setdefault(city, cc)
uk_core = open("src/lib/data/airportsUk.ts", encoding="utf-8").read().split("ALIAS_UK")[0]
core_has_uk = lambda c: re.search(r'(?:"%s"|\b%s): "' % (re.escape(c), re.escape(c)), uk_core) is not None

tz = json.load(open(W + "tz.json"))
pairs = collections.defaultdict(list)
for b in json.load(open(W + "wd.json")):
    if b["uk"] and re.search("[А-Яа-яІіЇїЄєҐґ]", b["uk"]):
        pairs[b["iata"]].append((b["en"], b["uk"]))

norm = lambda s: re.sub(r"[^a-z0-9]", "", unicodedata.normalize("NFD", s.lower()).encode("ascii", "ignore").decode())

def clean_name(n):
    n = re.sub(r"\b(International|Intl\.?|Airport|Aeropuerto|Aeroporto|Aéroport|Flughafen|Airfield|Regional|Municipal|Domestic)\b", "", n, flags=re.I)
    return re.sub(r"\s+", " ", n).strip(" -–,/") or n

def base_city(r):
    c = (r["municipality"] or "").strip() or clean_name(r["name"])
    c = re.sub(r"\s*\([^)]*\)\s*$", "", c)       # "Shanghai (Pudong)" -> "Shanghai"
    c = re.sub(r",\s*[A-Za-z .]+$", "", c)        # "Southend-on-Sea, Essex" -> "Southend-on-Sea"
    return OVERRIDE_CITY.get(r["iata_code"], c.strip())

order = {"large_airport": 0, "medium_airport": 1, "small_airport": 2}
size = {"large_airport": "L", "medium_airport": "M", "small_airport": "S"}
seen, sel = set(), []
for r in csv.DictReader(open(W + "airports.csv", encoding="utf-8")):
    code = r["iata_code"]
    if code and r["scheduled_service"] == "yes" and r["type"] in order and code not in have and code not in seen \
            and r["iso_country"] not in SKIP and r["iso_country"] != "UA":
        seen.add(code)
        sel.append(r)
sel.sort(key=lambda r: (order[r["type"]], r["iso_country"], r["name"]))

countries = collections.defaultdict(set)
for r in sel:
    countries[base_city(r)].add(r["iso_country"])

rows, ukmap = [], {}
for r in sel:
    base, cc, code = base_city(r), r["iso_country"], r["iata_code"]
    city = f"{base} ({cc})" if (base in cur_country and cur_country[base] != cc) or len(countries[base]) > 1 else base
    rows.append([code, OVERRIDE_NAME.get(code) or clean_name(r["name"]), city, cc, tz[code], round(float(r["latitude_deg"]), 4), round(float(r["longitude_deg"]), 4), size[r["type"]]])
    if city in ukmap or core_has_uk(city):
        continue
    ps = pairs.get(code, [])
    # Wikidata gives the city the airport serves, which can be a bigger neighbour (Omitama -> Tokyo): accept a label only when the
    # English names agree, otherwise leave the city in English rather than attach a wrong Ukrainian name.
    pick = next((uk for en, uk in ps if norm(en) == norm(base)), None) or next((uk for en, uk in ps if len(norm(base)) >= 4 and (norm(base) in norm(en) or norm(en) in norm(base))), None)
    if base in MANUAL_UK:
        pick = MANUAL_UK[base]
    if pick:
        ukmap[city] = pick

q = lambda s: json.dumps(s, ensure_ascii=False)
out = [
    'import type { Airport } from "@/lib/domain/types";', "",
    "// GENERATED by scripts/airports/generate.py from OurAirports (public domain, https://ourairports.com/data/): airports with scheduled",
    "// service and an IATA code; time zones from the coordinates (tz-lookup); Ukrainian city names from Wikidata. See docs/airports.md.",
    "// Do not edit by hand. size: L = large, M = medium, S = small airport.",
    'export type ExtraRow = [iata: string, name: string, city: string, country: string, tz: string, lat: number, lon: number, size: "L" | "M" | "S"];', "",
    'export const SIZE: Record<"L" | "M" | "S", NonNullable<Airport["size"]>> = { L: "large", M: "medium", S: "small" };', "",
    "export const ROWS_EXTRA: ExtraRow[] = [",
]
for r in rows:
    out.append("  [" + ", ".join([q(r[0]), q(r[1]), q(r[2]), q(r[3]), q(r[4]), str(r[5]), str(r[6]), q(r[7])]) + "],")
out += ["];", "", "export const CITY_UK_EXTRA: Record<string, string> = {"]
for k, v in sorted(ukmap.items()):
    out.append(f"  {q(k)}: {q(v)},")
out += ["};", ""]
open("src/lib/data/airportsExtra.ts", "w", encoding="utf-8").write("\n".join(out))
cities = {r[2] for r in rows}
print(f"{len(rows)} airports, {len(cities)} cities, {len(cities) - len([c for c in cities if c in ukmap])} cities kept English only")
