/// UI texts in Ukrainian and English. Look up with `s('key')`; `{name}` placeholders are filled from
/// the optional map. A key missing in the chosen language falls back to Ukrainian, then to the key.
class Strings {
  const Strings(this.lang);
  final String lang;

  String call(String key, [Map<String, Object>? args]) {
    var text = (lang == 'en' ? _en[key] : _uk[key]) ?? _uk[key] ?? key;
    args?.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    return text;
  }

  String get locale => lang == 'en' ? 'en' : 'uk';

  static Set<String> get ukKeys => _uk.keys.toSet();
  static Set<String> get enKeys => _en.keys.toSet();
}

final stringsProvider = Provider<Strings>((ref) => Strings(ref.watch(settingsProvider.select((s) => s.lang))));

